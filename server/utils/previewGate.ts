// Protected client preview. In production the site is PROTECTED by default: nothing is served without credentials, search engines are told to stay
// away, and money/file flows (checkout, payment webhooks, downloads) are switched off. Going public is a separate, explicit act
// (NUXT_PREVIEW_MODE=open). Everything here is pure so it can be unit-tested; server/middleware/00.preview-gate.ts applies the decision.
import { randomBytes, scryptSync, timingSafeEqual } from 'node:crypto'

export type PreviewMode = 'protected' | 'open'
export interface PreviewConfig { mode: PreviewMode; user: string; passwordHash: string }

export type GateDecision =
  | { action: 'allow'; headers: Record<string, string> }
  | { action: 'robots' }
  | { action: 'challenge'; failedAttempt: boolean }
  | { action: 'deny'; status: number; message: string }

export const NOINDEX_HEADERS = {
  'x-robots-tag': 'noindex, nofollow, noarchive, nosnippet',
  'cache-control': 'private, no-store',
  'referrer-policy': 'no-referrer',
} as const

/** Forced onto every response of a protected preview, whatever route rules or error pages set later. */
export const NO_STORE_HEADERS = { 'cache-control': 'private, no-store', 'cdn-cache-control': 'no-store', 'surrogate-control': 'no-store' } as const

/** Flows that must not run on a preview: checkout and payment webhooks (no live money), file downloads (no paid or unverified files served). */
export const PREVIEW_DISABLED_PATHS = [/^\/api\/checkout(\/|$)/, /^\/api\/webhooks(\/|$)/, /^\/api\/library\/download(\/|$)/]

/**
 * The one exception inside a disabled prefix: the list of payment methods the store can use. It moves no money and reveals nothing, and in a protected preview the
 * endpoint itself answers with an EMPTY list, so the storefront (footer, cart) learns "nothing to offer" without a failing request on every page.
 */
export const PREVIEW_ALLOWED_PATHS = [/^\/api\/checkout\/methods\/?$/]

const SCRYPT = { N: 16384, r: 8, p: 1, keylen: 32 }

/** `scrypt$N$r$p$<salt b64>$<hash b64>` — generated by scripts/preview/hash-password.mjs. The plain password is never stored. */
export function hashPassword(password: string, salt: Buffer = randomBytes(16)): string {
  const hash = scryptSync(password, salt, SCRYPT.keylen, { N: SCRYPT.N, r: SCRYPT.r, p: SCRYPT.p })
  return ['scrypt', SCRYPT.N, SCRYPT.r, SCRYPT.p, salt.toString('base64'), hash.toString('base64')].join('$')
}

export function parsePasswordHash(stored: string) {
  const [alg, n, r, p, salt, hash] = stored.split('$')
  const N = Number(n), R = Number(r), P = Number(p)
  if (alg !== 'scrypt' || !salt || !hash || ![N, R, P].every((v) => Number.isInteger(v) && v > 0) || N > 1 << 20 || N < 1024) return null
  const saltBuf = Buffer.from(salt, 'base64'), hashBuf = Buffer.from(hash, 'base64')
  return saltBuf.length >= 8 && hashBuf.length >= 16 ? { N, r: R, p: P, salt: saltBuf, hash: hashBuf } : null
}

export function verifyPassword(password: string, stored: string): boolean {
  const parsed = parsePasswordHash(stored)
  if (!parsed) return false
  try {
    const got = scryptSync(password, parsed.salt, parsed.hash.length, { N: parsed.N, r: parsed.r, p: parsed.p, maxmem: 256 * parsed.N * parsed.r })
    return timingSafeEqual(got, parsed.hash)
  } catch { return false }
}

export function parseBasicAuth(header: string | undefined | null): { user: string; password: string } | null {
  const m = /^Basic\s+([A-Za-z0-9+/=]+)$/i.exec((header ?? '').trim())
  if (!m) return null
  const text = Buffer.from(m[1]!, 'base64').toString('utf8')
  const i = text.indexOf(':')
  return i < 0 ? null : { user: text.slice(0, i), password: text.slice(i + 1) }
}

const eq = (a: string, b: string) => {
  const x = Buffer.from(a), y = Buffer.from(b)
  return x.length === y.length && timingSafeEqual(x, y)
}

export function normaliseMode(value: unknown, isProduction: boolean): PreviewMode {
  const v = String(value ?? '').trim().toLowerCase()
  if (v === 'open' || v === 'protected') return v
  return isProduction ? 'protected' : 'open' // unknown or empty never opens a production site
}

export function decide(input: { config: PreviewConfig; path: string; authorization?: string | null }): GateDecision {
  const { config } = input
  if (config.mode !== 'protected') return { action: 'allow', headers: {} }
  const path = input.path.split('?')[0]!
  if (path === '/robots.txt') return { action: 'robots' }
  // fail closed: a protected site without usable credentials serves nothing
  if (!config.user || !parsePasswordHash(config.passwordHash)) return { action: 'deny', status: 503, message: 'المعاينة غير مهيأة بعد' }
  const creds = parseBasicAuth(input.authorization)
  const userOk = creds ? eq(creds.user, config.user) : false
  const passOk = creds ? verifyPassword(creds.password, config.passwordHash) : false // always verified, so the timing does not reveal a valid user name
  if (!creds || !userOk || !passOk) return { action: 'challenge', failedAttempt: !!creds }
  if (!PREVIEW_ALLOWED_PATHS.some((re) => re.test(path)) && PREVIEW_DISABLED_PATHS.some((re) => re.test(path))) return { action: 'deny', status: 503, message: 'هذه الميزة غير متاحة في نسخة المعاينة' }
  return { action: 'allow', headers: { ...NOINDEX_HEADERS } }
}

export const ROBOTS_DISALLOW_ALL = 'User-agent: *\nDisallow: /\n'
